import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = resolve(root, "bundle/index.js");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/index.ts"],
  outfile: output,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  // Pi must supply its own SDK instances through its extension loader. Never
  // inline host packages (or the runtime dependencies installed by Pi).
  packages: "external",
  keepNames: true,
  write: false,
  metafile: true,
  banner: { js: "// Generated by npm run build:bundle. Edit src/, not this file." },
});

// An accidental native dependency bundle would create duplicate Pi registries.
// Internal imports must be flattened; external package imports stay external.
if (Object.keys(result.metafile.inputs).some(path => path.includes("node_modules/"))) {
  throw new Error("Extension bundle must not include dependencies from node_modules");
}
const text = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== text) {
    throw new Error("bundle/index.js is stale or missing; run npm run build:bundle and include it in the change");
  }
  console.log("Extension bundle is up to date");
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, text);
  console.log(`Built bundle/index.js (${Buffer.byteLength(text)} bytes)`);
}
